let currentTab = 0;
const totalTabs = 5;

function switchTab(tabIndex) {
  // Hide all tabs
  const allTabs = document.querySelectorAll(".tab-content");
  allTabs.forEach((tab) => tab.classList.add("hidden"));

  // Remove active state from all tab buttons
  const tabButtons = document.querySelectorAll(".tab-button");
  tabButtons.forEach((btn) => {
    btn.classList.remove("border-primary", "text-primary", "font-bold");
    btn.classList.add("border-transparent", "text-slate-500", "font-medium");
  });

  // Show selected tab
  document.getElementById(`tab-${tabIndex}`).classList.remove("hidden");

  // Add active state to selected tab button
  const activeButton = document.querySelector(`[data-tab="${tabIndex}"]`);
  activeButton.classList.remove(
    "border-transparent",
    "text-slate-500",
    "font-medium",
  );
  activeButton.classList.add("border-primary", "text-primary", "font-bold");

  currentTab = tabIndex;
  updateNavigation();
  updateProgress();
  updateSummary();
}

function nextTab() {
  if (currentTab < totalTabs - 1) {
    switchTab(currentTab + 1);
  }
}

function prevTab() {
  if (currentTab > 0) {
    switchTab(currentTab - 1);
  }
}

function updateNavigation() {
  const prevBtn = document.getElementById("prevBtn");
  const nextBtn = document.getElementById("nextBtn");
  const submitBtn = document.getElementById("submitBtn");

  // Show/hide Previous button
  if (currentTab > 0) {
    prevBtn.classList.remove("hidden");
  } else {
    prevBtn.classList.add("hidden");
  }

  // Show/hide Submit button
  if (currentTab === totalTabs - 1) {
    nextBtn.classList.add("hidden");
    submitBtn.classList.remove("hidden");
  } else {
    nextBtn.classList.remove("hidden");
    submitBtn.classList.add("hidden");
  }
}

function updateProgress() {
  const progress = ((currentTab + 1) / totalTabs) * 100;
  const progressText = document.getElementById("progressText");
  const progressBar = document.getElementById("progressBar");

  progressText.textContent = `Progress: ${Math.round(progress)}%`;
  progressBar.style.width = `${progress}%`;
}

function updateSummary() {
  const summaryItems = [
    "summary-basic",
    "summary-content",
    "summary-pricing",
    "summary-shipping",
    "summary-variants",
  ];

  summaryItems.forEach((itemId, index) => {
    const item = document.getElementById(itemId);
    if (item) {
      const icon = item.querySelector(".material-symbols-outlined");
      const text = item.querySelector("span:last-child");

      if (index <= currentTab) {
        icon.textContent = "check_circle";
        icon.classList.remove("text-slate-300");
        icon.classList.add("text-emerald-500");
        text.classList.remove("text-slate-400");
        text.classList.add("text-slate-600", "dark:text-slate-400");
      } else {
        icon.textContent = "radio_button_unchecked";
        icon.classList.remove("text-emerald-500");
        icon.classList.add("text-slate-300");
        text.classList.remove("text-slate-600", "dark:text-slate-400");
        text.classList.add("text-slate-400");
      }
    }
  });
}

function submitForm() {
  // Submit the form
  document.querySelector("form").submit();
}

function slugify(text) {
  return text
    .toString()
    .toLowerCase()
    .trim()
    .replace(/\s+/g, "-")
    .replace(/[^\w\-]+/g, "")
    .replace(/\-\-+/g, "-")
    .replace(/^-+/, "")
    .replace(/-+$/, "");
}

function generateSlug() {
  const nameField = document.getElementById("id_name");
  const slugField = document.getElementById("id_slug");

  if (nameField && slugField && nameField.value) {
    slugField.value = slugify(nameField.value);
  }
}

// Auto-generate slug as user types
document.addEventListener("DOMContentLoaded", function () {
  const nameField = document.getElementById("id_name");
  const slugField = document.getElementById("id_slug");

  if (nameField && slugField) {
    nameField.addEventListener("input", function () {
      if (!slugField.value || slugField.dataset.autoGenerated !== "false") {
        slugField.value = slugify(this.value);
        slugField.dataset.autoGenerated = "true";
      }
    });

    // Mark as manually edited if user types in slug field
    slugField.addEventListener("input", function () {
      this.dataset.autoGenerated = "false";
    });
  }
});
